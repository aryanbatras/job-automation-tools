#!/usr/bin/env node
// build.js
// Bundles the numbered modules into one function expression that the
// Playwright MCP can run with browser_run_code_unsafe.
//
// The bundle is self-contained: it embeds the user's preferences, the answers
// built from the confirmed profile, and the result of the preflight gate, all
// read from the local JSON files. A blocked preflight is compiled into the
// bundle, so the engine refuses to apply.

const fs = require('node:fs');
const path = require('node:path');
const childProcess = require('node:child_process');

const directory = __dirname;
const repositoryRoot = path.join(directory, '..', '..');
const outputDirectory = path.join(directory, 'dist');

const readJson = (file, fallback) => {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return fallback;
  }
};

const preferences = readJson(
  path.join(repositoryRoot, 'linkedin', 'content', 'local', 'preferences.json'),
  readJson(path.join(repositoryRoot, 'linkedin', 'content', 'examples', 'preferences.example.json'), null),
);

const profile = readJson(
  path.join(repositoryRoot, 'linkedin', 'content', 'local', 'profile.json'),
  {},
);

const answersFile = readJson(
  path.join(repositoryRoot, 'linkedin', 'content', 'local', 'pending-answers.json'),
  { entries: [] },
);

// The learned bank holds questions earlier runs answered. It is appended
// after the confirmed entries, so a confirmed label always wins the lookup.
const learnedBank = readJson(
  path.join(repositoryRoot, 'linkedin', 'content', 'local', 'learned-answers.json'),
  { answers: {} },
);
const answerEntries = require(path.join(
  repositoryRoot,
  'linkedin',
  'automation',
  'scripts',
  'record-answers.js',
)).composeAnswers(answersFile.entries || [], learnedBank);

const preflight = (() => {
  const script = path.join(repositoryRoot, 'linkedin', 'automation', 'scripts', 'profile_store.py');
  const python = path.join(repositoryRoot, '.venv', 'bin', 'python');
  for (const command of [python, 'python3']) {
    try {
      const output = childProcess.execFileSync(command, [script, 'preflight'], { encoding: 'utf8' });
      return JSON.parse(output);
    } catch (error) {
      if (error.stdout) {
        try {
          return JSON.parse(error.stdout);
        } catch {
          // fall through to the next candidate
        }
      }
    }
  }
  return { status: 'blocked', checks: { profile: 'preflight_not_run' } };
})();

const moduleFiles = fs
  .readdirSync(directory)
  .filter((name) => /^\d\d-[a-z0-9-]+\.js$/.test(name))
  .sort();

if (moduleFiles.length === 0) {
  console.error('no modules found');
  process.exit(1);
}

const pageDirectory = path.join(directory, 'page');
const pageFiles = fs
  .readdirSync(pageDirectory)
  .filter((name) => /^\d\d-[a-z0-9-]+\.js$/.test(name))
  .sort();

if (pageFiles.length === 0) {
  console.error('no page runtime fragments found');
  process.exit(1);
}

// The fragments share one `helpers` object and are composed into a single
// page function: only one function can cross into the page, and helpers must
// not depend on anything outside it.
const pageRuntime = `// ---- page runtime ----\nconst pageRuntime = () => {
const helpers = {};
${pageFiles
  .map((name) => `// page/${name}\n${fs.readFileSync(path.join(pageDirectory, name), 'utf8')}`)
  .join('\n')}
window.__JAT_HELPERS__ = helpers;
return true;
};
const installHelpers = (page) => page.evaluate(pageRuntime);`;

const parts = [
  pageRuntime,
  ...moduleFiles.map((name) => {
    const source = fs.readFileSync(path.join(directory, name), 'utf8');
    return `// ---- ${name} ----\n${source}`;
  }),
];

const engine = fs.readFileSync(path.join(directory, 'engine.js'), 'utf8');

const bundle = `// Generated by linkedin/automation/build.js. Do not edit by hand.
async (page, providedConfig) => {
const EMBEDDED_PREFERENCES = ${JSON.stringify(preferences)};
const EMBEDDED_ANSWERS = ${JSON.stringify(answerEntries)};
const EMBEDDED_PREFLIGHT = ${JSON.stringify(preflight)};
const EMBEDDED_PROFILE = ${JSON.stringify(profile)};
${parts.join('\n')}
// ---- engine.js ----
${engine}
  return await runEngine(page, providedConfig);
}
`;

// The in-page bundle runs the same engine inside a page that another tool
// drives: it carries the page shim, skips the search navigation and applies
// to the jobs that are already listed.
const shimSource = fs
  .readFileSync(path.join(directory, 'browser', 'page-shim.js'), 'utf8')
  .split('if (typeof module')[0]
  .trim();

const stripComments = (source) =>
  source
    .split('\n')
    .filter((line) => !/^\s*\/\//.test(line))
    .filter((line) => line.trim() !== '')
    .join('\n');

const inPageParts = parts.filter((part) => !part.includes('02-search.js'));

const inPageBundle = `// Generated by linkedin/automation/build.js. Do not edit by hand.
async (options) => {
${stripComments(shimSource)}
const EMBEDDED_PREFERENCES = ${JSON.stringify(preferences)};
const EMBEDDED_ANSWERS = ${JSON.stringify(answerEntries)};
const EMBEDDED_PREFLIGHT = ${JSON.stringify(preflight)};
const EMBEDDED_PROFILE = ${JSON.stringify(profile)};
const page = createPageShim();
${stripComments(inPageParts.join('\n'))}
${stripComments(engine)}
window.__JAT_API__ = { runEngine, runJobsOnPage, applyOne, openApply, collectJobs, collectJobsWhenReady, selectJobs, installHelpers, installConfig };
if (options && options.install) {
  window.__JAT__ = null;
  window.__JAT_PAGE__ = page;
  window.__JAT_PREFS__ = EMBEDDED_PREFERENCES;
  window.__JAT_ANSWERS__ = EMBEDDED_ANSWERS;
  window.__JAT_PROFILE__ = EMBEDDED_PROFILE;
  await installHelpers(page);
  return { installed: true, api: Object.keys(window.__JAT_API__) };
}
const config = {
  preferences: EMBEDDED_PREFERENCES,
  answers: EMBEDDED_ANSWERS,
  preflight: EMBEDDED_PREFLIGHT,
  profile: EMBEDDED_PROFILE,
};
const gate = await preflight(page, config);
if (!gate.ok) {
  return { status: 'blocked', reason: 'preflight_failed', errors: gate.errors, results: [], gaps: [] };
}
return await runJobsOnPage(page, config, options && options.limit);
}
`;

fs.mkdirSync(outputDirectory, { recursive: true });
const outputPath = path.join(outputDirectory, 'linkedin-apply.js');
fs.writeFileSync(outputPath, bundle);

const inPagePath = path.join(outputDirectory, 'linkedin-inpage.js');
fs.writeFileSync(inPagePath, inPageBundle);

// The per-job script and the answers map, for a page that another tool
// drives. The map keeps the question text for the ordinary fields and a
// short "years:<technology>" alias for the recurring experience questions.
const answerMap = {};
for (const entry of answerEntries) {
  const label = String(entry.label || '').trim();
  if (!label) continue;
  const years = label.match(/years of (?:total |work )?experience(?: do you have)?(?: with)? ([a-z0-9+#.]+)/i);
  if (years) {
    answerMap[`years:${years[1].toLowerCase()}`] = entry.value;
    continue;
  }
  answerMap[label] = entry.value;
}
const answersPath = path.join(outputDirectory, 'linkedin-answers.json');
fs.writeFileSync(answersPath, `${JSON.stringify(answerMap, null, 2)}\n`);

const preferencesPath = path.join(outputDirectory, 'linkedin-preferences.json');
fs.writeFileSync(preferencesPath, `${JSON.stringify(preferences, null, 2)}\n`);

const applyJobPath = path.join(outputDirectory, 'apply-job.js');
fs.writeFileSync(
  applyJobPath,
  fs.readFileSync(path.join(directory, 'browser', 'apply-job.js'), 'utf8'),
);

// The jobs filter panel is driven from the page itself: LinkedIn drops the
// workplace and experience filters from the URL on redirect.
const searchModule = stripComments(fs.readFileSync(path.join(directory, '02-search.js'), 'utf8'));
const filtersPath = path.join(outputDirectory, 'apply-filters.js');
fs.writeFileSync(
  filtersPath,
  `// Generated by linkedin/automation/build.js. Do not edit by hand.
async (page) => {
const PREFERENCES = ${JSON.stringify(preferences)};
${searchModule}
return await applySearchFilters(page, PREFERENCES);
}
`,
);

// One file a driver can run to put the in-page engine and the per-job
// entry point on the current tab. It never navigates, so a run cannot lose
// its page half way through.
const installPath = path.join(outputDirectory, 'install-inpage.js');
fs.writeFileSync(
  installPath,
  `// Generated by linkedin/automation/build.js. Do not edit by hand.
async (page) => {
  const installed = await page.evaluate(${JSON.stringify(`(${inPageBundle})({ install: true })`)});
  await page.evaluate(${JSON.stringify(fs.readFileSync(path.join(directory, 'browser', 'apply-job.js'), 'utf8'))});
  const job = await page.evaluate(() => typeof window.__JAT_JOB__);
  return { ...installed, job };
}
`,
);

process.stdout.write(
  JSON.stringify({
    status: 'ok',
    output: path.relative(process.cwd(), outputPath),
    inPage: path.relative(process.cwd(), inPagePath),
    answersMap: path.relative(process.cwd(), answersPath),
    preferencesMap: path.relative(process.cwd(), preferencesPath),
    applyJob: path.relative(process.cwd(), applyJobPath),
    modules: moduleFiles,
    answers: answerEntries.length,
    preflight: preflight.status,
    bytes: bundle.length,
    inPageBytes: inPageBundle.length,
  }) + '\n',
);
